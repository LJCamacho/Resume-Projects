package clickDragCircle;

import java.awt.*;

public class rectangle {
	//instance variables
	private int base, height;
	private int x, y;
	private Color color;
	
	//constructor
	public rectangle(int x, int y, int base, int height, Color color) {
		this.x = x;
		this.y = y;
		this.base = base;
		this.height = height;
		this.color = color;
	}//end rectangle
	
}//end rectangle
